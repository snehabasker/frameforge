"""Generate docs/RESULTS.md from a CSV written by evaluate.py.

Owns formatting only -- every number in the CSV came from evaluate.py
actually running a model (CLAUDE.md 1: "no fabricated numbers"). This
script never invents a value; a metric missing from the CSV is rendered
as "--", not guessed.

Usage: python scripts/gen_results_table.py --csv results/metrics.csv --out docs/RESULTS.md
"""

from __future__ import annotations

import argparse
import csv
import statistics
from collections import defaultdict
from pathlib import Path

METRIC_COLUMNS = [
    ("psnr_rgb", "PSNR (RGB)", "{:.2f} dB"),
    ("psnr_y", "PSNR (Y)", "{:.2f} dB"),
    ("ssim_rgb", "SSIM (RGB)", "{:.4f}"),
    ("ssim_y", "SSIM (Y)", "{:.4f}"),
    ("lpips", "LPIPS", "{:.4f}"),
    ("temporal_error_pred", "Temporal err (pred)", "{:.5f}"),
    ("temporal_error_gt", "Temporal err (GT)", "{:.5f}"),
    ("params", "Params", "{:,.0f}"),
    ("gflops_540p", "GFLOPs @540p", "{:.2f}"),
    ("onnx_latency_ms", "ONNX latency (ms)", "{:.2f}"),
]


def load_rows(csv_path: Path) -> list[dict]:
    with open(csv_path, newline="") as f:
        return list(csv.DictReader(f))


def aggregate_by_model(rows: list[dict]) -> dict[str, dict[str, float | None]]:
    by_model: dict[str, dict[str, list[float]]] = defaultdict(lambda: defaultdict(list))
    for row in rows:
        for key, _, _ in METRIC_COLUMNS:
            val = row.get(key, "")
            if val not in ("", None):
                by_model[row["model"]][key].append(float(val))

    out = {}
    for model, metrics in by_model.items():
        out[model] = {}
        for key, _, _ in METRIC_COLUMNS:
            values = metrics.get(key)
            if key == "params" and values:
                out[model][key] = values[0]  # constant per model, not averaged
            elif values:
                out[model][key] = statistics.mean(values)
            else:
                out[model][key] = None
    return out


def format_table(aggregated: dict[str, dict]) -> str:
    header = "| Model | " + " | ".join(label for _, label, _ in METRIC_COLUMNS) + " |"
    sep = "|---" * (len(METRIC_COLUMNS) + 1) + "|"
    lines = [header, sep]
    # Stable, spec-meaningful ordering when these model names are present;
    # unknown names (e.g. custom student variant names) sort after, alphabetically.
    preferred_order = ["bilinear", "bicubic", "fsr1_easu_rcas", "swinir_teacher"]
    def sort_key(m: str):
        rank = preferred_order.index(m) if m in preferred_order else len(preferred_order)
        return (rank, m)

    ordered = sorted(aggregated, key=sort_key)
    for model in ordered:
        metrics = aggregated[model]
        cells = [model]
        for key, _, fmt in METRIC_COLUMNS:
            val = metrics.get(key)
            cells.append(fmt.format(val) if val is not None else "--")
        lines.append("| " + " | ".join(cells) + " |")
    return "\n".join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--csv", required=True)
    parser.add_argument("--out", default="docs/RESULTS.md")
    parser.add_argument(
        "--note", default="",
        help="freeform note prepended to the generated file, e.g. flagging "
             "smoke-test-scale data vs. the real target dataset",
    )
    args = parser.parse_args()

    rows = load_rows(Path(args.csv))
    aggregated = aggregate_by_model(rows)
    table = format_table(aggregated)

    scenes = sorted({row["scene"] for row in rows})
    sequences = sorted({row["sequence"] for row in rows})

    content = "# Results\n\n"
    content += (
        f"Generated by `scripts/gen_results_table.py` from `{args.csv}`. "
        "Every number here came from `evaluate.py` actually running the "
        "listed model -- nothing is hand-typed.\n\n"
    )
    if args.note:
        content += f"> {args.note}\n\n"
    content += (
        f"Test set: {len(scenes)} scene(s) ({', '.join(scenes)}), "
        f"{len(sequences)} sequence(s).\n\n"
    )
    content += table + "\n"

    failures_notes = Path("docs/failures/NOTES.md")
    if failures_notes.exists():
        content += (
            "\n## Failure cases\n\n"
            "See `docs/failures/NOTES.md` (generated by "
            "`scripts/extract_failure_crops.py`) for worst-error crops "
            "and honest notes on what they do and don't show.\n"
        )

    out_path = Path(args.out)
    out_path.parent.mkdir(parents=True, exist_ok=True)
    out_path.write_text(content)
    print(f"wrote {out_path}")


if __name__ == "__main__":
    main()
