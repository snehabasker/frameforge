"""Extract worst-error crops for failure-case analysis (CLAUDE.md section 6:
"Automatically extract crops with the worst error... Save before/after
crops to docs/failures/ and write short honest notes in RESULTS.md.").

Finds the highest-L1-error windows between a model's prediction and ground
truth for a given sequence, and saves side-by-side before (bicubic
upsample)/after (model output)/ground-truth crop images.

Category labels (disocclusion / thin geometry / fast motion / specular
highlight) need real content with those features to identify meaningfully;
the synthetic fixture used elsewhere in this repo is a smooth analytic
pattern with none of them (see docs/DECISIONS.md D0). This script's crop
EXTRACTION mechanism is real and runs end to end; the category labels
below are honest placeholders pending the real rendered dataset -- see
the generated notes file, which says this explicitly rather than
pretending to categorize what it can't.
"""

from __future__ import annotations

import argparse
from pathlib import Path

import torch
import torch.nn.functional as F
import yaml
from PIL import Image

from frameforge.data.dataset import FrameSequenceDataset


def find_worst_crops(
    pred: torch.Tensor, target: torch.Tensor, crop_size: int, top_k: int
) -> list[tuple[int, int, int, float]]:
    """Returns [(frame_idx, y0, x0, mean_abs_error), ...] for the `top_k`
    highest-error non-overlapping crop_size x crop_size windows, via a
    simple sliding-window mean-abs-error scan (stride = crop_size // 2).
    """
    t, c, h, w = pred.shape
    stride = max(1, crop_size // 2)
    candidates = []
    err = (pred - target).abs().mean(dim=1)  # (T, H, W)
    for frame_idx in range(t):
        for y0 in range(0, h - crop_size + 1, stride):
            for x0 in range(0, w - crop_size + 1, stride):
                window_err = err[frame_idx, y0:y0 + crop_size, x0:x0 + crop_size].mean().item()
                candidates.append((frame_idx, y0, x0, window_err))
    candidates.sort(key=lambda c: -c[3])

    selected: list[tuple[int, int, int, float]] = []
    for cand in candidates:
        overlaps = any(
            cand[0] == s[0] and abs(cand[1] - s[1]) < crop_size and abs(cand[2] - s[2]) < crop_size
            for s in selected
        )
        if not overlaps:
            selected.append(cand)
        if len(selected) >= top_k:
            break
    return selected


def save_crop_triplet(
    out_dir: Path, tag: str, before: torch.Tensor, after: torch.Tensor, gt: torch.Tensor
):
    def to_img(t: torch.Tensor) -> Image.Image:
        arr = (t.clamp(0, 1) * 255).round().byte().permute(1, 2, 0).numpy()
        return Image.fromarray(arr)

    pad = 2
    h, w = before.shape[-2:]
    grid = Image.new("RGB", (w * 3 + pad * 4, h + pad * 2), (20, 20, 20))
    for i, tile in enumerate([before, after, gt]):
        grid.paste(to_img(tile), (pad + i * (w + pad), pad))
    out_dir.mkdir(parents=True, exist_ok=True)
    grid.save(out_dir / f"{tag}.png")


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--data-root", required=True)
    parser.add_argument("--data-config", default="configs/data.yaml")
    parser.add_argument("--checkpoint", required=True)
    parser.add_argument("--scenes", nargs="*", default=None)
    parser.add_argument("--crop-size", type=int, default=32)
    parser.add_argument("--top-k", type=int, default=6)
    parser.add_argument("--out-dir", default="docs/failures")
    args = parser.parse_args()

    with open(args.data_config) as f:
        data_cfg = yaml.safe_load(f)
    dataset = FrameSequenceDataset(
        args.data_root, data_cfg["exr_channel_map"], data_cfg["tonemap"], scenes=args.scenes
    )

    from frameforge.models.student import FrameForgeNet
    from frameforge.train import run_unroll

    ckpt = torch.load(args.checkpoint, map_location="cpu", weights_only=True)
    model = FrameForgeNet(
        variant=ckpt["variant"], channels=ckpt["channels"], num_blocks=ckpt["num_blocks"]
    ).eval()
    model.load_state_dict(ckpt["model_state"])

    out_dir = Path(args.out_dir)
    notes = ["# Failure-case crops\n",
             "Generated by `scripts/extract_failure_crops.py`. Each PNG is "
             "[bicubic upsample | model output | ground truth] side by side, "
             "cropped to the window with the worst mean-|error| for that "
             "sequence/frame.\n",
             "\n**Category labels (disocclusion/thin geometry/fast motion/"
             "specular highlight) are not assigned below.** They need real "
             "geometry and materials to identify meaningfully; the data "
             "available in this environment is the synthetic analytic "
             "fixture (see docs/DECISIONS.md D0), which has none of those "
             "features. Re-run this script once the real rendered dataset "
             "exists to get genuinely categorized failure crops.\n"]

    for i in range(len(dataset)):
        sample = dataset[i]
        with torch.no_grad():
            pred = run_unroll(model, sample)
        before = F.interpolate(sample.lr_rgb, scale_factor=model.scale, mode="bicubic",
                                align_corners=False).clamp(0, 1)

        worst = find_worst_crops(pred, sample.hr_rgb, args.crop_size, args.top_k)
        notes.append(f"\n## {sample.scene}/{sample.sequence}\n")
        notes.append("| Crop | Frame | Position | Mean \\|error\\| |")
        notes.append("|---|---|---|---|")
        for frame_idx, y0, x0, err_val in worst:
            tag = f"{sample.scene}_{sample.sequence}_f{frame_idx}_{y0}_{x0}"
            save_crop_triplet(
                out_dir, tag,
                before[frame_idx, :, y0:y0 + args.crop_size, x0:x0 + args.crop_size],
                pred[frame_idx, :, y0:y0 + args.crop_size, x0:x0 + args.crop_size],
                sample.hr_rgb[frame_idx, :, y0:y0 + args.crop_size, x0:x0 + args.crop_size],
            )
            notes.append(f"| `{tag}.png` | {frame_idx} | ({x0},{y0}) | {err_val:.4f} |")

    (out_dir / "NOTES.md").write_text("\n".join(notes))
    print(f"wrote crops + notes to {out_dir}")


if __name__ == "__main__":
    main()
